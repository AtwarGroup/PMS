import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const page=readFileSync(new URL('../admin/users.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../assets/css/admin-accounts.css',import.meta.url),'utf8');
const definition=page.split('\n').find(line=>line.startsWith('const errorText=e=>'));
assert.ok(definition,'Error formatting helper must exist');
const errorText=vm.runInNewContext(`${definition};errorText`);
assert.equal(errorText({error:{message:'Account update rejected'}}),'Account update rejected');
assert.equal(errorText({message:'[object Object]'}),'تعذر إكمال الطلب. يرجى تحديث الصفحة والمحاولة مجددًا.');
assert.match(page,/if\(coreChanged\)\{const result=await invoke\(body\)/);
assert.match(page,/if\(accessChanged\)\{const permission=await sb\.rpc/);
assert.match(page,/if\(detailsChanged\)\{const result=await sb\.rpc/);
assert.match(page,/completed\.length\?' \(حُفظت:/);
assert.match(page,/document\.body\.style\.visibility='visible'/);
assert.match(page,/class="account-card"/);
assert.match(css,/\.account-list\{display:grid;grid-template-columns:repeat\(2/);
assert.match(css,/\.account-editor\[hidden\]/);
console.log('Account error formatting, staged saves and responsive card layout passed.');
